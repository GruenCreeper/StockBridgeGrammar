using Newtonsoft.Json;

namespace StockBridgeGrammar.Models
{
    // A member joins two nodes. Stock assignment and grammar rules use
    // geometry and topology without chord, diagonal, or bay classifications.
    public class BridgeMember
    {
        [JsonProperty("id")]      public string Id     { get; set; }
        [JsonProperty("from")]    public string From   { get; set; }
        [JsonProperty("to")]      public string To     { get; set; }
        [JsonProperty("length")]  public double Length { get; set; }

        // Assignment-side fields (filled by the Assigner).
        [JsonProperty("assignedStockId", NullValueHandling = NullValueHandling.Ignore)]
        public string AssignedStockId { get; set; }

        // Unique physical piece id generated by the assigner (for example
        // "S1#2"). AssignedStockId remains the inventory-type id so older
        // Grasshopper definitions can continue to group members by stock type.
        [JsonProperty("assignedStockPieceId", NullValueHandling = NullValueHandling.Ignore)]
        public string AssignedStockPieceId { get; set; }

        [JsonProperty("status", NullValueHandling = NullValueHandling.Ignore)]
        public string Status { get; set; }  // "ok" | "unsafe" | "unresolved"

        [JsonProperty("utilization", NullValueHandling = NullValueHandling.Ignore)]
        public double? Utilization { get; set; }

        [JsonProperty("waste", NullValueHandling = NullValueHandling.Ignore)]
        public double? Waste { get; set; }

        [JsonProperty("curveGuid", NullValueHandling = NullValueHandling.Ignore)]
        public string CurveGuid { get; set; }

        // Axial force (kN), signed: + tension / − compression.
        // Supplied directly or through VGS Force Adapter for Section Check.
        [JsonProperty("force", NullValueHandling = NullValueHandling.Ignore)]
        public double? Force { get; set; }
    }
}
